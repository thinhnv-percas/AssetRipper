			}
			else
			{
				metadata.AddMethodDebugInformation(default(DocumentHandle), default(BlobHandle));
			}
		}
		list2.SortBy<(MethodDefinitionHandle, MethodDefinitionHandle), MethodDefinitionHandle>(((MethodDefinitionHandle MoveNextMethod, MethodDefinitionHandle KickoffMethod) row) => row.MoveNextMethod);
		foreach (var item2 in list2)
		{
			metadata.AddStateMachineMethod(item2.Item1, item2.Item2);
		}
		list4.SortBy<(MethodDefinitionHandle, GuidHandle, BlobHandle), MethodDefinitionHandle>(((MethodDefinitionHandle Parent, GuidHandle Guid, BlobHandle Blob) row) => row.Parent);
		foreach (var item3 in list4)
		{
			metadata.AddCustomDebugInformation(item3.Item1, item3.Item2, item3.Item3);
		}
		list3.SortBy<(DocumentHandle, GuidHandle, BlobHandle), DocumentHandle>(((DocumentHandle Parent, GuidHandle Guid, BlobHandle Blob) row) => row.Parent);
		foreach (var item4 in list3)
		{
			metadata.AddCustomDebugInformation(item4.Item1, item4.Item2, item4.Item3);
		}
		DebugDirectoryEntry entry = file.Reader.ReadDebugDirectory().FirstOrDefault((DebugDirectoryEntry dir) => dir.Type == DebugDirectoryEntryType.CodeView);
		BlobContentId contentId = new BlobContentId(file.Reader.ReadCodeViewDebugDirectoryData(entry).Guid, entry.Stamp);
		PortablePdbBuilder portablePdbBuilder = new PortablePdbBuilder(metadata, GetRowCounts(reader), entryPoint, (IEnumerable<Blob> blobs) => contentId);
		BlobBuilder blobBuilder = new BlobBuilder();
