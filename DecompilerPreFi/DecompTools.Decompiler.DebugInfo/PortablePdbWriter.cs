				localSignatureRowId = ((!methodBody.LocalSignature.IsNil) ? MetadataTokens.GetRowNumber(methodBody.LocalSignature) : 0);
			}
			else
			{
				MethodBodyBlock methodBody = null;
				localSignatureRowId = 0;
			}
			if (sequencePoints != null && sequencePoints.Count > 0)
			{
				sequencePointBlobs.Add(methodDefinitionHandle2, (document, EncodeSequencePoints(metadata, localSignatureRowId, sequencePoints)));
			}
			else
			{
				sequencePointBlobs.Add(methodDefinitionHandle2, (default(DocumentHandle), default(BlobHandle)));
			}
		}
	}

	private static BlobHandle WriteSourceToBlob(MetadataBuilder metadata, string sourceText, out byte[] sourceCheckSum)
	{
		//IL_0016: Unknown result type (might be due to invalid IL or missing references)
		//IL_001c: Expected O, but got Unknown
		BlobBuilder blobBuilder = new BlobBuilder();
		using (MemoryStream memoryStream = new MemoryStream())
		{
			DeflateStream val = new DeflateStream((Stream)memoryStream, (CompressionLevel)0, true);
			byte[] bytes = Encoding.UTF8.GetBytes(sourceText);
			((Stream)(object)val).Write(bytes, 0, bytes.Length);
			((Stream)(object)val).Close();
			byte[] buffer = memoryStream.ToArray();
			blobBuilder.WriteInt32(bytes.Length);
			blobBuilder.WriteBytes(buffer);
			SHA256 val2 = SHA256.Create();
			try
			{
				sourceCheckSum = ((HashAlgorithm)val2).ComputeHash(bytes);
			}
			finally
			{
				((IDisposable)val2)?.Dispose();
			}
		}
		return metadata.GetOrAddBlob(blobBuilder);
	}

	private static BlobHandle EncodeSequencePoints(MetadataBuilder metadata, int localSignatureRowId, List<SequencePoint> sequencePoints)
	{
		if (sequencePoints.Count == 0)
		{
			return default(BlobHandle);
		}
		BlobBuilder blobBuilder = new BlobBuilder();
		blobBuilder.WriteCompressedInteger(localSignatureRowId);
		int num = -1;
		int num2 = -1;
		int num3 = -1;
		checked
		{
			for (int i = 0; i < sequencePoints.Count; i++)
			{
				SequencePoint sequencePoint = sequencePoints[i];
				if (i > 0)
				{
					blobBuilder.WriteCompressedInteger(sequencePoint.Offset - num);
				}
				else
				{
					blobBuilder.WriteCompressedInteger(sequencePoint.Offset);
				}
				num = sequencePoint.Offset;
				if (sequencePoint.IsHidden)
				{
					blobBuilder.WriteInt16(0);
					continue;
				}
				int num4 = sequencePoint.EndLine - sequencePoint.StartLine;
				int value = sequencePoint.EndColumn - sequencePoint.StartColumn;
				blobBuilder.WriteCompressedInteger(num4);
				if (num4 == 0)
				{
					blobBuilder.WriteCompressedInteger(value);
				}
				else
				{
					blobBuilder.WriteCompressedSignedInteger(value);
				}
				if (num2 < 0)
				{
					blobBuilder.WriteCompressedInteger(sequencePoint.StartLine);
					blobBuilder.WriteCompressedInteger(sequencePoint.StartColumn);
				}
				else
				{
					blobBuilder.WriteCompressedSignedInteger(sequencePoint.StartLine - num2);
					blobBuilder.WriteCompressedSignedInteger(sequencePoint.StartColumn - num3);
				}
				num2 = sequencePoint.StartLine;
				num3 = sequencePoint.StartColumn;
			}
			return metadata.GetOrAddBlob(blobBuilder);
		}
	}

	private static ImmutableArray<int> GetRowCounts(MetadataReader reader)
	{
		ImmutableArray<int>.Builder builder = ImmutableArray.CreateBuilder<int>(MetadataTokens.TableCount);
		for (int i = 0; i < MetadataTokens.TableCount; i = checked(i + 1))
		{
			builder.Add(reader.GetTableRowCount((TableIndex)checked((byte)i)));
		}
		return builder.MoveToImmutable();
	}

	private static string SyntaxTreeToString(SyntaxTree syntaxTree, DecompilerSettings settings)
	{
		StringWriter stringWriter = new StringWriter();
		TokenWriter writer = new TextWriterTokenWriter(stringWriter);
		syntaxTree.AcceptVisitor(new InsertParenthesesVisitor
		{
			InsertParenthesesForReadability = true
		});
		writer = TokenWriter.WrapInWriterThatSetsLocationsInAST(writer);
		syntaxTree.AcceptVisitor(new CSharpOutputVisitor(writer, settings.CSharpFormattingOptions));
		return stringWriter.ToString();
	}
