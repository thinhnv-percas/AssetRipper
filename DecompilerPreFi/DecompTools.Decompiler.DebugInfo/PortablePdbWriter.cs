		List<(DocumentHandle, GuidHandle, BlobHandle)> list3 = new List<(DocumentHandle, GuidHandle, BlobHandle)>();
		List<(MethodDefinitionHandle, GuidHandle, BlobHandle)> list4 = new List<(MethodDefinitionHandle, GuidHandle, BlobHandle)>();
